def make_tile(key: str, face: int, block_idx: int) -> bytes:
    base = palette(key, face)
    seed = int.from_bytes(hashlib.sha256(f'{key}:{face}:{block_idx}'.encode()).digest()[:8], 'big')
    rng = random.Random(seed)
    k = key.lower()
    pixels = []
    for y in range(TILE):
        for x in range(TILE):
            n = rng.randint(-12, 12)
            r, g, b = base
            # Material-specific patterns keep the 284 definitions visually distinct.
            if 'ore' in k:
                cluster = ((x * 7 + y * 11 + block_idx * 3) % 17)
                if cluster in (0, 1, 2, 3): n += 48
                elif cluster in (4, 5): n -= 16
            elif 'log' in k:
                if face != FACE_SIDE:
                    radius = math.sqrt((x - 7.5) ** 2 + (y - 7.5) ** 2)
                    n += 18 if int(radius) % 3 == 0 else -5
                else:
                    n += int(math.sin((x + block_idx % 5) * 0.75) * 9)
                    if x % 5 == 0: n -= 9
            elif 'plank' in k or 'wood' in k or 'door' in k or 'fence' in k or 'chest' in k or 'sign' in k:
                n += int(math.sin((y + block_idx % 4) * 1.15) * 8)
                if y % 5 == 0: n -= 10
            elif 'brick' in k or 'stonebrick' in k:
                if y in (0, 7, 8, 15) or (x + (7 if y >= 8 else 0)) % 8 == 0: n -= 24
            elif 'stone' in k or 'cobble' in k or 'rock' in k or 'andesite' in k or 'granite' in k or 'diorite' in k:
                if (x * 5 + y * 9 + block_idx) % 19 in (0, 1): n -= 20
                elif (x * 3 + y * 7 + block_idx) % 23 == 0: n += 24
            elif 'leaves' in k or 'grass' in k or 'sapling' in k or 'plant' in k or 'bamboo' in k or 'seagrass' in k or 'wheat' in k:
                if (x * 3 + y * 5 + block_idx) % 7 == 0: n += 27
                if (x + y + block_idx) % 11 == 0: n -= 13
            elif 'glass' in k or 'pane' in k or 'ice' in k:
                if x in (1, 2, 13, 14) or y in (1, 2, 13, 14): n += 28
                elif (x + y + block_idx) % 9 == 0: n -= 5
            elif 'sand' in k or 'gravel' in k:
                if (x + y * 3 + block_idx) % 9 == 0: n += 16
            elif 'water' in k:
                if (y + (x // 4) + block_idx) % 5 == 0: n += 14
            elif 'lava' in k or k == 'fire' or 'magma' in k:
                if (x * 7 + y * 3 + block_idx) % 11 < 3: n += 42
            elif 'wool' in k or 'carpet' in k:
                if (x + y) % 5 == 0: n -= 6
            elif 'redstone' in k:
                if (x * 5 + y * 13 + block_idx) % 13 < 3: n += 32

            if key == 'grass' and face == FACE_SIDE and y < 3:
                r, g, b = (74, 143, 55)
            if key == 'grass' and face == FACE_BOTTOM:
                r, g, b = (119, 78, 49)

            a = 255
            if 'glass' in k or 'pane' in k:
                a = 108
                if x in (0, 1, 14, 15) or y in (0, 1, 14, 15): a = 198
            elif 'water' in k or 'bubble_column' in k:
                a = 158
            elif 'lava' in k or k == 'fire':
                a = 224
            elif 'ice' in k:
                a = 158
            elif 'leaves' in k:
                a = 0 if (x * 13 + y * 7 + block_idx) % 17 == 0 else 218
            elif 'slime' in k:
                a = 182
            elif 'web' in k:
                a = 198
            elif 'portal' in k or 'end_gateway' in k:
                a = 190
            pixels.append((max(0, min(255, r + n)), max(0, min(255, g + n)), max(0, min(255, b + n)), a))
    return b''.join(bytes(px) for px in pixels)

def png_chunk(tag: bytes, data: bytes) -> bytes:
    return struct.pack('>I',len(data))+tag+data+struct.pack('>I',zlib.crc32(tag+data)&0xffffffff)

def save_png(path: pathlib.Path, rgba: bytes):
    # RGBA 8 bit PNG, no third-party image library required.
    raw=b''.join(b'\x00'+rgba[y*WIDTH*4:(y+1)*WIDTH*4] for y in range(HEIGHT))
    data=b'\x89PNG\r\n\x1a\n'+png_chunk(b'IHDR',struct.pack('>IIBBBBB',WIDTH,HEIGHT,8,6,0,0,0))+png_chunk(b'IDAT',zlib.compress(raw,9))+png_chunk(b'IEND',b'')
    path.parent.mkdir(parents=True,exist_ok=True); path.write_bytes(data)

