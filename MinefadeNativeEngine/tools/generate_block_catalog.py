def ident(key: str) -> str:
    # Bedrock 1.8 names are mostly snake_case, with a few legacy camelCase entries.
    parts = re.split(r'[^A-Za-z0-9]+', key)
    name = ''.join(p[:1].upper()+p[1:] for p in parts if p)
    if not name or name[0].isdigit(): name = 'Block'+name
    return name

def display_name(key: str) -> str:
    if key in ES: return ES[key]
    words = key.replace('_',' ').replace('2',' II').replace('Arm',' brazo ').replace('Collision',' colisión')
    return ' '.join(w.capitalize() if w.islower() else w for w in words.split())

def classify(key: str, block: dict) -> tuple[str,int,float,str,int,int]:
    k = key.lower()
    tex = block.get('textures', '')
    sound = str(block.get('sound',''))
    if 'textures' in block and isinstance(tex, dict):
        tex_top = str(tex.get('up', tex.get('north', tex.get('side',''))))
        tex_side = str(tex.get('side', tex.get('north', tex_top)))
        tex_bottom = str(tex.get('down', tex.get('side', tex_top)))
    else:
        tex_top = tex_side = tex_bottom = str(tex)
    if k == 'air' or k in {'info_update','info_update2','movingblock','reserved6','pistonarmcollision','structure_void'}:
        shape='None'; flags=0; hardness=0.0; tool='None'; light=0; stack=64
    elif k in {'barrier','invisiblebedrock'}:
        shape='None'; flags=1; hardness=-1.0; tool='None'; light=0; stack=64
    elif k in {'water','flowing_water','lava','flowing_lava','bubble_column'}:
        shape='Fluid'; flags=4|8; hardness=100.0 if 'lava' in k else 100.0; tool='None'; light=15 if 'lava' in k else 0; stack=64
    elif (any(w in k for w in ['sapling','tallgrass','seagrass','flower','mushroom','deadbush','wheat','beetroot','double_plant','sea_pickle','coral_fan','bamboo_sapling','nether_wart','carrots','potatoes']) and
          not k.endswith('_mushroom_block') and k != 'nether_wart_block'):
        shape='CrossPlant'; flags=16; hardness=0.0; tool='None'; light=3 if 'sea_pickle' in k else 0; stack=64
    elif 'slab' in k and not k.startswith('double_'):
        shape='Slab'; flags=1|2; hardness=1.5; tool='Pickaxe'; light=0; stack=64
    elif 'stairs' in k:
        shape='Stairs'; flags=1|2; hardness=2.0 if 'wood' in sound else 1.5; tool='Axe' if 'wood' in sound else 'Pickaxe'; light=0; stack=64
    elif 'pane' in k or k in {'iron_bars'}:
        shape='Pane'; flags=1|4; hardness=0.3; tool='Pickaxe'; light=0; stack=64
    elif 'fence' in k or k.endswith('_gate') or k in {'cobblestone_wall','mossy_cobblestone_wall'}:
        shape='Fence'; flags=1|2; hardness=2.0; tool='Axe' if 'wood' in sound else 'Pickaxe'; light=0; stack=64
    elif 'trapdoor' in k:
        shape='Trapdoor'; flags=1|2; hardness=3.0 if 'iron' in k else 3.0; tool='Pickaxe' if 'iron' in k else 'Axe'; light=0; stack=64
    elif 'door' in k or 'standing_sign' in k or 'wall_sign' in k or 'banner' in k:
        shape='Door'; flags=1|2; hardness=3.0; tool='Axe'; light=0; stack=64
    elif k in {'fire','portal','end_portal','end_gateway'}:
        shape='CrossPlant' if k=='fire' else 'Thin'; flags=16|4; hardness=-1.0 if k in {'portal','end_portal','end_gateway'} else 0.0; tool='None'; light=15 if k=='fire' else 0; stack=64
    elif k in {'bed','cake','daylight_detector','daylight_detector_inverted','turtle_egg','waterlily','bamboo','end_rod'}:
        shape='Thin'; flags=1|2; hardness=0.5; tool='None'; light=14 if k=='end_rod' else 0; stack=64
    elif any(w in k for w in ['rail','redstone_wire','torch','ladder','lever','pressure_plate','button','carpet','snow_layer','tripwire','vine','standing_sign','wall_sign','frame','cocoa','flower_pot']):
        shape='Thin'; flags=16; hardness=0.5; tool='None'; light=14 if 'torch' in k else 0; stack=64
    elif k in {'glass','stained_glass','ice','packed_ice','blue_ice','frosted_ice','leaves','leaves2','web','slime','stained_glass_pane'}:
        shape='Cube'; flags=1|4; hardness=0.3; tool='Pickaxe' if 'glass' in k or 'ice' in k else 'Shears'; light=0; stack=64
    elif 'scaffolding' in k:
        shape='Scaffolding'; flags=1|4; hardness=0.5; tool='None'; light=0; stack=64
    else:
        shape='Cube'; flags=1|2; tool='Pickaxe'; hardness=1.5; light=0; stack=64
        if k == 'bedrock': hardness=-1.0
        elif 'obsidian' in k: hardness=50.0
        elif any(w in k for w in ['dirt','sand','gravel','farmland','path','grass']): hardness=0.6; tool='Shovel'
        elif any(w in k for w in ['log','planks','wood','hay','bookshelf','jukebox','noteblock']): hardness=2.0; tool='Axe'
        elif any(w in k for w in ['ore','stone','brick','prismarine','netherrack','nether_brick','quartz','cobble','furnace']): hardness=3.0 if 'ore' in k else 1.5
        elif any(w in k for w in ['gold','iron','diamond','emerald','lapis','copper']): hardness=5.0; tool='Pickaxe'
        if ('glowstone' in k or 'sealantern' in k or 'glowingobsidian' in k or
            'beacon' in k or 'conduit' in k or 'lit_redstone_lamp' in k): light=15
        if 'lit_furnace' in k: light=13
        if 'end_rod' in k: light=14
        if 'lit_redstone_ore' in k: light=9
    # Minefade interaction flags: visible/creatable blocks get an explicit placement bit.
    if k not in {'air','info_update','info_update2','movingblock','reserved6','pistonarmcollision','invisiblebedrock','structure_void','barrier','fire','portal','end_portal','end_gateway','bubble_column'}:
        flags |= 64
    if light > 0:
        flags |= 32
    # More specific flags for light / transparent materials.
    if any(w in k for w in ['glass','ice','leaves','web','slime','water','lava','portal','stained_glass','coral_fan']):
        flags = (flags | 4) & ~2
    if k in {'air','info_update','info_update2','movingblock','reserved6','pistonarmcollision','invisiblebedrock','structure_void','barrier','fire','portal','end_portal','end_gateway','bubble_column'}:
        drop = 0
    elif k == 'flowing_water': drop = 9
    elif k == 'flowing_lava': drop = 11
    elif k == 'lit_furnace': drop = 74
    elif k == 'lit_redstone_ore': drop = 91
    elif k == 'lit_redstone_lamp': drop = 147
    elif k == 'lit_pumpkin': drop = 106
    elif k == 'powered_repeater': drop = 115
    elif k == 'powered_comparator': drop = 184
    elif k == 'double_stone_slab': drop = 57
    elif k == 'double_stone_slab2': drop = 220
    elif k == 'double_wooden_slab': drop = 200
    else: drop = -1  # default to self; resolved by registry consumer
    return shape,flags,hardness,tool,light,stack,drop,tex_top,tex_side,tex_bottom,sound

